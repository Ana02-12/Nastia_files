def f(ls):
    cnt = 0  # голоса текущего кандидата
    gh = None  # кандидат

    for x in ls:
        # все голоса за этого кандидата
        # были уничтожены
        if cnt == 0:
            gh = x
        # кандидат получил голос
        if x == gh:
            cnt += 1
        # встретили его соперника
        else:
            cnt -= 1
    # вернем того, кто не уничтожился
    return gh