def reverseBits(self, n: int) -> int:
    #инициализируем результат
    res = 0
    #проходим по каждому биту числа
    for _ in range(32):
        #освободим место для записи
        res = res << 1
        #берем последний бит числа
        last = n & 1
        #и удалим его из изначального числа
        n = n >> 1
        #запишем его в конец
        res = res | last
    return res

